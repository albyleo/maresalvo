import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

test('atlas renderer prioritizes the latest target, shares decoded frames and aborts on teardown', async () => {
  const manifest = JSON.parse(await readFile('src/components/home/ocean-frames.json', 'utf8'));
  const source = (await readFile('src/components/home/oceanSequence.ts', 'utf8')).replace("import manifest from './ocean-frames.json';", `const manifest = ${JSON.stringify(manifest)};`);
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
  const requests = [], images = [], draws = [], rafs = new Map(); let count = 0, resize;
  let inFlight = 0, maxInFlight = 0;
  globalThis.fetch = (url, options) => new Promise(resolve => {
    inFlight++; maxInFlight = Math.max(maxInFlight, inFlight);
    requests.push({ url, signal: options.signal, finish() { inFlight--; resolve({ ok: true, blob: async () => new Blob(['atlas']) }); } });
  });
  globalThis.Image = class { decode() { return new Promise(resolve => { this.finish = resolve; images.push(this); }); } };
  globalThis.document = { hidden: false, addEventListener() {}, removeEventListener() {} };
  globalThis.ResizeObserver = class { constructor(fn) { resize = fn; } observe() {} disconnect() {} };
  globalThis.requestAnimationFrame = fn => { rafs.set(++count, fn); return count; };
  globalThis.cancelAnimationFrame = id => rafs.delete(id);
  const tick = async () => { for (let i=0; i<4; i++) await new Promise(resolve => setImmediate(resolve)); };
  const paint = () => { const jobs = [...rafs.values()]; rafs.clear(); jobs.forEach(fn => fn()); };
  const canvas = { clientWidth: 390, clientHeight: 844, dataset: {}, getContext: () => ({ drawImage: (...args) => draws.push(args) }) };
  const { createOceanSequence } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
  const sequence = createOceanSequence(canvas);
  assert.equal(requests.length, 2);
  requests[0].finish(); await tick();
  sequence.update(1); images[0].finish(); await tick(); paint();
  assert.equal(draws.length, 0, 'a late old sheet cannot replace the requested frame');
  requests[1].finish(); await tick();
  const last = requests.find(request => request.url.endsWith('atlas-11.webp'));
  assert.ok(last); last.finish(); await tick();
  const lastImage = images.at(-1); lastImage.finish(); await tick(); paint();
  assert.equal(draws.at(-1)[0], lastImage);
  assert.deepEqual(draws.at(-1).slice(1,5), [1280,1920,320,480]);
  const decodeCount = images.length;
  sequence.update(298/299); paint();
  assert.deepEqual(draws.at(-1).slice(1,5), [960,1920,320,480]);
  assert.equal(images.length, decodeCount, 'adjacent frames share the same decode');
  assert.equal(maxInFlight, 2);
  assert.equal(canvas.width, 390);
  canvas.clientWidth = 400; resize(); paint(); assert.equal(canvas.width, 400);
  sequence.destroy(); assert.ok(requests.every(request => request.signal.aborted));
  const requested = requests.length; sequence.update(0); await tick();
  assert.equal(requests.length, requested); assert.equal(canvas.dataset.ready, undefined);
});
